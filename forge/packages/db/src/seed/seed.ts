  await insertAll(db, s.productReviews, productReviewRows);

  // Sanity check on the leaderboard the community page renders.
  const consistency = CHALLENGES[0]!;
  void buildLeaderboard(
    consistency,
    participantRows
      .filter((row) => row.challengeSlug === consistency.slug)
      .map((row) => ({ userId: row.userId, displayName: 'Member', value: row.value ?? 0, visible: row.visible ?? true })),
  );

  return {
    users: userRows.length,
    coaches: coachRows.length,
    plans: planRows.length,
    workouts: workoutCount,
    setLogs: setRows.length,
    recipes: recipeRows.length,
    products: PRODUCTS.length,
    posts: postRows.length,
    demoLogin: { email: MEMBERS[0]!.email, password: DEMO_PASSWORD },
  };
