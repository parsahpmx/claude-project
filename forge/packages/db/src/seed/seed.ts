/**
 * Seed the demo dataset.
 *
 * Deterministic end to end: ids come from a seeded generator and every date is
 * derived from the `today` argument, so two seed runs on the same day produce
 * byte-identical rows. That is what lets tests assert on real data and lets a
 * screenshot in the docs stay accurate.
 *
 * The plans, sessions, loads and personal records here are not hand-written
 * fixtures — they are generated by running the same `@forge/core` engines the
 * live product runs. If the progression engine changes, the demo data changes
 * with it, and a seeded member is indistinguishable from a real one.
 */

export interface SeedResult {
  users: number;
  coaches: number;
  plans: number;
  workouts: number;
  setLogs: number;
  recipes: number;
  products: number;
  posts: number;
  demoLogin: { email: string; password: string };
}

export const DEMO_PASSWORD = 'ForgeDemo!2026';

const CHUNK = 200;

/** PGlite chokes on very large single INSERTs; batching keeps memory flat. */
async function insertAll<T>(
  db: DatabaseHandle['db'],
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  table: any,
  rows: T[],
): Promise<void> {
  for (let i = 0; i < rows.length; i += CHUNK) {
    const slice = rows.slice(i, i + CHUNK);
    if (slice.length > 0) await db.insert(table).values(slice as never).execute();
  }
}

